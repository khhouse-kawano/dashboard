/**
 * 台帳の日付文字列を、⚠️ **その端末の時間帯**の 0時 として読む。
 *
 * ─────────────────────────────────────────────
 * ⚠️⚠️ **JavaScript は区切り文字で解釈を変える。**
 *
 *   ⚠️ `new Date('2026-05-31')` … ⚠️⚠️ **UTC の 0時**（⚠️ 日本では同じ日の 9時）
 *   ⚠️ `new Date('2026/05/31')` … ⚠️ **その端末の 0時**
 *
 * ⚠️ ⚠️ **期間の終わりは `new Date(year, month, 0)` で作っており、こちらは端末の 0時。**
 *   ⚠️ そのため ⚠️⚠️ **ハイフンで読むと終了月の末日だけが「9時間はみ出して」範囲から落ちる。**
 *
 * ⚠️ ⚠️ **実際に起きていた**（2026-09-29 / v2.2.154 で修正）。
 *   ⚠️ 建売の 2025/06〜2026/05 で、⚠️ **2026/05/31 の反響 7件・接触3・来場1・申込1** が
 *     ⚠️ 画面から丸ごと欠けていた。⚠️ **分析API（SQLで比較）とだけ数が合わなかった。**
 *
 * ⚠️⚠️ **スラッシュへ寄せること。** ⚠️ ハイフンへ寄せてはならない。
 *   ⚠️ ⚠️ **どちらの形で来ても端末の 0時として読める。**
 * ─────────────────────────────────────────────
 *
 * ⚠️ 空文字や読めない値は `Invalid Date` を返す。
 *   ⚠️ ⚠️ **比較すると必ず false になる**ので、期間を指定していれば自然に外れる。
 */
export const toLocalDate = (value: string | null | undefined): Date =>
    new Date(String(value ?? '').replace(/-/g, '/'));
