-- ============================================================================
-- homes_db_resale: userId の重複行を掃除する
--
--   背景
--     handlers/homes_db_resale.php の重複チェックが別テーブル（homes_db_kaeru）を
--     見ており、両テーブルに共通の userId が無いため判定が常に空振りしていた。
--     結果、GAS が回るたびに INSERT され続け、実測で 4,756行 / userId 38種
--     （1つの userId に最大616行）まで膨張している。
--
--     ハンドラ側は homes_db_resale を見るよう修正済み。これ以上増えないので、
--     このSQLは**過去分の掃除**であり、急いで流す必要はない。
--
--   影響範囲
--     ・inquiry_customer_resale は inquiry_id が UNIQUE のため無傷（38件）
--     ・brokerage_listings の同期も userId ごとに最新1行しか見ないため無傷
--     ・つまり掃除しなくても業務データは正しい。テーブルが太っているだけ。
--
--   実行: docker exec -i dashboard-mariadb-db-1 \
--           mariadb -ulocal_user -plocal_password local_db < このファイル
--
--   冪等性: 既に1行だけの userId は削除対象にならないため、再実行しても安全。
--
--   ⚠ 先に必ずバックアップを取ること
--     mysqldump ... local_db homes_db_resale > homes_db_resale_backup.sql
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 手順1. 実行前の状態を確認
-- ---------------------------------------------------------------------------
SELECT
    COUNT(*)                  AS `総行数`,
    COUNT(DISTINCT userId)    AS `userIdの種類`,
    COUNT(*) - COUNT(DISTINCT userId) AS `削除される見込み`
FROM homes_db_resale;

-- ---------------------------------------------------------------------------
-- 手順2. userId ごとに no が最大の1行だけを残して削除
--
--   最新（no が最大）を残すのは、ハンドラが UPDATE ではなく INSERT を
--   繰り返していたため、後の行ほど新しい内容になっているから。
--
--   MariaDB は「削除対象テーブルを副問い合わせで直接参照する」ことを
--   許さないため、一段かませて派生テーブルにしている。
-- ---------------------------------------------------------------------------
DELETE FROM homes_db_resale
WHERE no NOT IN (
    SELECT keep_no FROM (
        SELECT MAX(no) AS keep_no
        FROM   homes_db_resale
        GROUP  BY userId
    ) AS keepers
);

-- ---------------------------------------------------------------------------
-- 手順3. 結果確認（総行数 = userIdの種類 になっていること）
-- ---------------------------------------------------------------------------
SELECT
    COUNT(*)               AS `総行数`,
    COUNT(DISTINCT userId) AS `userIdの種類`
FROM homes_db_resale;

