## 見方
- 上のカードに、期間の中の実行の回数と、成功・一部失敗・失敗の数が出ます
- 「**24時間以上成功していないタスク**」は、取り込みが止まっている可能性のあるものの数です。0 でないときは、下の表で確かめてください

### タスクごとの最新
取り込みの種類（タスク）ごとに、いちばん新しい結果と、**最後に成功した日時**が出ます。
- 最後の成功が24時間以上前のもの・記録が無いものは**赤**で、上に並びます
- 「7日の失敗」は、直近7日の一部失敗・失敗の回数です
- タスクの名前を押すと、そのタスクの履歴だけが下に出ます

### 履歴
1回の実行が1行です。期間・タスク・状態で絞れます。見出しを押すと並べ替えられます。
- **成功**：最後まで動き、失敗はありませんでした
- **一部失敗**：最後まで動きましたが、途中で失敗がありました（例：いえらぶの3店舗のうち、1店舗の物件が取れなかった）
- **失敗**：途中で止まりました（例：ログインできなかった）
- 失敗があった行は「**理由を見る**」を押すと、理由の全文が開きます

> 注意：記録は180日分です。それより古いものは自動で消えます。

> 要確認：失敗が続くときは、理由を開いて、システムの担当者に伝えてください。ポータルのパスワードの変更や、ポータル側の画面の変更で止まることがあります。

