-- -------------------------------------------------------------
-- ご質問やご要望（任意入力）
--
-- ⚠️⚠️ **入力は任意である。** 未入力でも反響は受け付け、同期もできる。
--   ⚠️ 空文字ではなく NULL で保存する（他の任意項目と揃えている）。
--   ⚠️ **NULL と '' が混ざると画面の出し分けが効かなくなる。**
--
-- ⚠️ 連絡方法・連絡時間の希望が書かれる想定のため、**改行が入る。**
--   ⚠️ VARCHAR ではなく TEXT にしている。
--
-- ⚠️⚠️ **顧客として同期するとき、この内容は master_data.remarks へ引き継がれる。**
--   ⚠️ 引き継がないと、営業が見る画面（master_data）からは消える。
--   ⚠️ 既存の「紹介アンバサダー」「建築希望地」と同じ備考欄に、
--     ⚠️ **行を分けて追記される**（features/ambassador/index.ts）。
-- -------------------------------------------------------------
ALTER TABLE `inquiry_ambassador`
  ADD COLUMN `message` TEXT DEFAULT NULL COMMENT 'ご質問やご要望（任意入力。顧客本人が記入）'
  AFTER `build_area`;

