## 反響単価設定
反響1件あたりの仕入れの単価（円）です。チームサマリーの反響費用と獲得単価に使います。空欄は0円として扱います。

## 営業テンプレート（定型文）
売り反響・買い反響で使う定型文です（30件まで）。本文には次の言葉を入れておくと、使うときに置き換わります。
- {{name}}：顧客名
- {{staff}}：担当者
- {{addr}}：物件所在地
- {{property}}：問合せ物件
- {{price}}：価格・予算
- {{today}}：本日

## 宅建業者情報
契約書の「乙」欄と記名押印欄に印字する、会社の情報です。

## 以前のアプリのデータを取り込む（マスターだけ）
以前のアプリの全データ（反響・商談・媒介台帳・買取再販・変更履歴など）と、設定・週次行動計画・コンプライアンスを、Dashboard に取り込んで最新にします。この節は権限が「マスター」の人にだけ表示されます。

1. 以前のアプリの「⚙ 設定・データ管理」で「🔄 サーバーから再取得」を押す
2. 同じ画面の「📥 バックアップを保存（JSON・書類除く）」を押す（「営業管理バックアップ_日付.json」が保存される）
3. Dashboard の設定画面の一番下で、そのファイルを選ぶ
4. 種類ごとの件数（新規・更新・そろえる・重複・非表示）を確かめて「取り込む」を押す

- 同じポータル反響が両方にあるときは、以前のアプリの内容にそろえます
- 非表示にする範囲は2つから選びます（行は消さないので戻せます）
  - **全面差し替え**（はじめから選ばれています）：ファイルに無い行はすべて非表示。Dashboard のポータル取り込みで入った反響も、以前のアプリに無ければ非表示になります
  - 以前のアプリで消えた行だけ非表示：Dashboard で入った行は残します
- 何度取り込んでも同じ結果になります。途中で止まったときは、同じファイルでもう一度取り込みます

> 注意：設定・週次行動計画・コンプライアンスは、以前のアプリの内容で丸ごと置き換わります。

