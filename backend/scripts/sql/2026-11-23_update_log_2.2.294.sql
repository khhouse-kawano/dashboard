## 期間を選ぶ
- いちばん上の「開始月」「終了月」で、表に出す月を選びます。選択肢は新しい月から並んでいます
- はじめは、今月までの6か月が出ます
- 選べるのは12か月までです。それより長くなる選び方をすると、もう片方の月が自動で寄ります（例：開始月を前にずらすと、終了月が開始月から12か月目になります）
- 期間を変えると、その期間の分だけを読み込み直します。「読み込んでいます」「集計しています」と出ている間は、少し待ってください
- 「合計」の列は、表に出ている月の合計です

> ヘッダーの「架電状況」から開いたときは、選んだ期間がブラウザの上のアドレス（URL）にも入ります。読み込み直しても同じ期間で開き、アドレスを送れば同じ期間の表を見てもらえます。

## 表示を選ぶ（注文営業・建売営業）
- 「表示カテゴリを選択」で、店舗ごとの担当者の表を出します。注文営業では「インサイドセールス」「土地新着ネット」も選べます
- 期間を変えても、選んだ表示はそのまま残ります

