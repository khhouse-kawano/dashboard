## 商談・架電記録から検索
ページ送りの右の「**商談・架電記録**」の枠で、商談記録・架電記録に書いた内容からお客様を探せます（2026年11月から）。
- 枠の欄に言葉を入れて、「**商談・架電記録から検索**」を押すか Enter を押します。入力しただけでは探しません
- 上の絞り込み（店舗・ランク・ステータスなど）は**そのまま残り**、その中から、記録にその言葉があるお客様に絞り込みます
- 探している間は、一覧に「商談・架電内容」の列が増えます（担当営業とステータスの間）。当てはまった記録が「日付・架電か商談か（と、そのときの内容）・記録の文」の形で、新しい順に5件まで出ます。6件目からは「ほか ○ 件」とだけ出ます
- 言葉は**空白（全角・半角）で区切ると、5つまで並べられます**。枠の「**すべて含む**」「**いずれかを含む**」で合わせ方を選びます（初めは「すべて含む」）
  - すべて含む：そのお客様の記録のどこかに、すべての言葉があるお客様（1つの記録にそろっていなくても、架電記録と商談記録に分かれていても当たります）
  - いずれかを含む：どれか1つでも言葉があるお客様
- 記録の文は、探した言葉の前後だけが出ます。文の中の探した言葉は、どれも**黄色の太字**です。一覧に出る記録は、どれかの言葉を含む記録です
- 英字の大文字と小文字は区別しません
- 「**解除**」を押すと、記録での絞り込みをやめて、列も消えます。ほかの絞り込みは残ります
- 探した言葉と合わせ方もアドレス（URL）に入るので、読み込み直しても、送った相手も同じ一覧を開けます

> 注意：記録の全部から探すため、1回に数秒かかります。件数の右に「読み込み中…」と出ている間は待ってください。

> 注意：サーバーの片方に届かず、全件を読み込む方法に切り替わっているときは、この検索は使えません（枠に「この検索は今は使えません」と出ます）。

> 注意：検索がうまくいかなかったときは、枠に赤で「記録の検索に失敗しました（理由）」と出て、一覧は検索の前のまま残ります。もう一度「商談・架電記録から検索」を押すと探し直します。何度も出るときは、出ている理由を添えて管理者に知らせてください。

