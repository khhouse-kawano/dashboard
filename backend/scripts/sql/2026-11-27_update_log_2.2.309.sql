## 見られるもの
- 上のカード：該当件数、今期の着工棟数、着工予定、建築中、販売中、販売中で広告が未出稿の物件の数
  - カードの数は、絞り込みに合う物件から数えます。たとえば「県」を宮崎県にすると、宮崎県の物件の数になります
- 一覧：物件ID・物件名称・工程状況・販売状況・県・エリア・チーム・販売価格 など
  - 「表示項目」で、出す項目を選べます（約40項目。選んだ項目は次に開いたときも残ります）

> 着工棟数・着工予定は、用途が建売の物件を「基礎着工日」で数えます。モデルハウス・注文住宅・土地のみ・キャンセルの物件は数えません。今期は6月から今日まで、着工予定は基礎着工日が明日以降の物件です。

## 使い方
- 開いたときは30件だけ出ます。一覧を下までスクロールすると、次の30件が出ます
- 上の欄で、物件名称・物件ID、工程状況、販売状況、県、チーム（係）、広告出稿、Instagram で絞り込めます
- 一覧の見出しを押すと、その項目の順に並べ替えます。もう一度押すと逆の順になります。空の欄の物件は、いちばん下に出ます
- 絞り込み・並べ替えの条件は、画面のアドレスにも付きます。アドレスを開き直すと、同じ一覧が出ます
- 「広告出稿」「Instagram」の列のスイッチを押すと、出稿済み・投稿済みを記録できます。この2つのほかは、この画面から変えられません

## 物件台帳を新しくする（物件更新）
一覧の数字は、最後に取り込んだときのものです。SatBase の「KHF物件管理【KHG】 - 中間加工（物件）」を CSV で書き出し、「物件更新」から取り込みます。
- 物件IDで照らし合わせ、ある物件は上書き、ない物件は追加します。CSV にない物件は消しません
- 広告出稿・Instagram の記録は、取り込んでも消えません

> 要確認：取り込みの頻度（毎週・毎月など）と担当を決めてください。取り込まないと、着工棟数などの数字が古いままになります。
