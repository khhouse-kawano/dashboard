## 月の並び（店舗別）
店舗別反響推移の表は、左から「全期間」、続いて新しい月から古い月の順に並びます。左端は終了月です（終了月を選んでいなければ今月）。
- 「期間を反転」にチェックを入れると、古い月から新しい月の順に変わります
- 並びを変えても、数は変わりません

> 注意：「サマリ」で開くグラフと表は、チェックに関係なく古い月から順に並びます。

## 数え方
[[反響日起算と実績日起算]] の「実績日起算」です。
- 実来場：その月に初回面談があった人
- 次アポ：来場した月に数える
- 契約：契約日の月に数える
- 来場予約数（店舗別）：実来場 ＋ キャンセル

> 注意：[[販促媒体別広告費]] とは数え方が違うので、同じ月でも数字が合わないことがあります。

数字を押すと、そのお客様の一覧が開きます。

