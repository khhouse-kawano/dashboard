- **反響合計**（括弧内は未同期）
- **反響目標**：営業の人数 × 8（1か月）
- **来場合計**：初回面談の月で数える
- **来場目標**：営業の人数 × 4

## 列の見方
- **重複**：氏名・携帯・メールのうち2つ以上が同じ、別の反響があると表示されます
- **顧客タグ**：重複／ギフト券進呈済み／業者／ブラックリスト（ブラックリストは理由を入れて登録。下の「ブラックリストに登録する」）
- **流入**（反響媒体の下の青い札）：ホームページの反響で、広告などから来た情報があるときに出ます。札には流入元（Google など）が出ます。押すと、顧客IDと、その人がいつ・どの広告からサイトに来たかが見られます
  - 灰色の「流入：ID」は、広告の情報が無く顧客IDだけがあるもの（自然検索・直接の訪問など）です

## 流入履歴の見方
- **顧客ID**：サイトがお客様ごとに振るIDです。「コピー」で写せます
- **流入元・キャンペーン**：反響と一緒に届いた広告の情報です
- **広告からの着地**：同じお客様が広告からサイトに来た記録（新しい順）。問い合わせの前に何回来ていたかが分かります

> 注意：タグを貼る前の反響には札が出ません。タグについては [[アクセス解析]] を見てください。

> 注意：ひらがなのフリガナは、取込のときにカタカナへ自動で直ります。

## 期間を変えたとき
開始月・終了月を変えると、その期間の反響だけを読み込み直します。全部の期間を一度に読まないので、画面の表示が速くなります。
- 店舗・課・媒体・取込状況・氏名・住所などの絞り込みは、そのまま残ります
- 上の集計も、選んだ期間の分で数えます（数え方は今までと同じです）
- 読み込みが終わるまで、少しのあいだ前の期間の表示が残ることがあります
- 「重複」の表示は、選んだ期間に関係なく、これまでに届いたすべての反響と見比べます（今までどおり）

## 期間は画面のアドレスに残ります
開始月・終了月を選ぶと、ブラウザの上に出ているアドレス（URL）の末尾に、選んだ期間が付きます。
- 再読み込み（F5）をしても、同じ期間のまま開きます
- ブラウザの「戻る」を押すと、ひとつ前に選んでいた期間に戻ります
- アドレスをコピーして送ると、相手も同じ期間で反響一覧を開けます（開くのは、相手がいま選んでいる事業の反響一覧です）
- 左のメニューから「反響一覧」を押し直すと、はじめの期間（前月〜今月）に戻ります

> 注意：店舗・媒体・氏名などの絞り込みはアドレスに残りません。再読み込みすると、期間のほかははじめの状態に戻ります。

## 再読み込み
上の「🔄 再読み込み」を押すと、絞り込み（期間・店舗・氏名など）はそのままで、新しく届いた反響を読み直します。

## ブラックリストに登録する
顧客タグの「ブラックリスト」を押すと、小さな画面が開きます。**理由**を入れて「登録」を押すと登録されます。
- 理由が空のままでは登録できません
- 理由は、ヘッダーの「反響管理 → ブラックリスト設定」の**備考**に日付つきで残ります。同じ人をもう一度登録したときは、前の理由の下に書き足されます
- 外すとき（もう一度押す）は、理由の画面は出ません

## 個人情報削除
