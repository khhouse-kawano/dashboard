-- -------------------------------------------------------------
-- ⚠️ 1列にまとめず、2列に分ける。
--   どちらが失敗したかで対応がまったく違うため。
--
--     mail_sent   … 顧客が「受け付けられたか分からない」状態になる。
--                   気づいたら個別に連絡すればよい。
--     notify_sent … **社内が反響に気づかない。**
--                   ダッシュボードを見ない日が続くと追客が丸ごと遅れる。
--
--   まとめると「失敗した」としか分からず、どちらを追えばよいか判断できない。
--
-- ⚠️ NULL と 0 は意味が違う。
--     NULL … まだ送っていない（この機能より前に届いた反響を含む）
--     0    … 送ろうとして失敗した ← こちらだけが対応の必要な状態
--   既定値を 0 にしてはいけない。過去の反響がすべて「失敗」に見える。
-- -------------------------------------------------------------
ALTER TABLE `inquiry_ambassador`
  ADD COLUMN `mail_sent` TINYINT DEFAULT NULL
    COMMENT '顧客宛サンクスメール。1=成功 0=失敗 NULL=未送信'
  AFTER `agreed`;

ALTER TABLE `inquiry_ambassador`
  ADD COLUMN `notify_sent` TINYINT DEFAULT NULL
    COMMENT '社内宛通知メール。1=成功 0=失敗 NULL=未送信'
  AFTER `mail_sent`;

