## タグがすること
- サイトを見た人**全員**に、**顧客ID**を振ります（同じブラウザなら、日をまたいでも同じID）
- 広告（Google・Meta・Yahoo!）や、utm の付いたURLから来たときは、その情報を覚えます。**フォームの無いLPに着地しても**消えません
- フォームから問い合わせると、顧客IDと広告の情報が、反響と一緒に届きます
- 反響一覧（注文営業）の「流入」から、その人がいつ・どの広告から来たかを見られます（[[反響一覧]]）
- 見たページを1ページずつ記録します。反響になった人と、有効名簿になった人の記録は、ずっと残します（それ以外の人の古い記録は、件数が多くなったら消します）

> 注意：顧客IDは**サイト（ドメイン）ごと**です。kh-house.jp と day-just-house.com では別のIDになります。

## サイトを登録する
1. 「サイトを登録」を押す
2. サイト名・ブランドを入れる
3. 「許可するオリジン」に、タグを貼るサイトの **https://ドメイン** を入れる（例：https://kh-house.jp。/ 以降は不要。www の有り無しが両方あるなら2行）
4. 「保存する」→ そのサイトのタグが開きます

## タグを入れる
「タグ」を押すと、2種類のタグが出ます。サイトに合わせて**どちらか一方だけ**を使います。

- **GTM（Googleタグマネージャー）を使っているサイト**：「GTM 用」をコピーし、GTM で新しいタグ（カスタム HTML）に貼ります。トリガーは「All Pages」にして、公開します
- **GTM を使っていないサイト**：「フッター用」をコピーし、サイトの**すべてのページ**のフッターに**1回だけ**貼ります。WordPress の場合は、WPCode の Footer 欄、またはテーマのフッターに貼ります
- 入れたあと、広告のURL（例：?utm_source=test）でサイトを開くと、「直近30日の着地」「最後の着地」が増えます

> 注意：GTM に「フッター用」を貼っても動きません（GTM が中身を作り直すときに、サイトを見分ける情報が消えるため）。GTM には必ず「GTM 用」を使ってください。

> 注意：GTM とフッターの両方に入れると、着地が2回記録されます。GTM に切り替えたら、フッターのタグは外してください。

> 注意：LP がサイトと別の仕組み（単体のページなど）で作られていて、GTM もフッターも入っていない場合は、その LP にも入れてください。LP とフォームのドメインが違うと、広告の情報と顧客IDはフォームまで届きません。

> 注意：ここに無いドメインからの記録は保存しません。ドメインを変えたら「直す」で許可するオリジンも直してください。

## 一覧の見方
- **直近30日の着地**：広告から来た訪問の数です
- **直近30日のCV**：直近30日に届いた反響のうち、問い合わせの日までにそのサイトに来ていた人の数です（広告以外から来た人も含みます）
- 1人の人が複数のサイトに来ていれば、それぞれのサイトで1件と数えます
- 「再読み込み」を押すと、一覧と開いているサマリーを最新にします

## サイトのサマリー
サイト名を押すと、その行の下にサマリーが開きます。もう一度押すと閉じます。ほかのサイトのサマリーとは別に開け閉めできます。
- 上の数字：直近30日の**PV**（広告以外も含む）、そのうち**広告から**の分、**CV**、**CV率**（CV ÷ PV）
- 「**着地ページ**」「**流入元**」のタブで、表の軸を切り替えます
- 表の見出しを押すと並べ替えができます
- 「着地ページ」の表では、ページのアドレスを押すと、そのページが別のタブで開きます
- 流入元は、広告の utm_source（例：meta、google）か、広告以外なら「organic/google」（自然検索）「social/instagram」（SNS）「referral/ドメイン」（他のサイト）「direct」（直接）です
- CV は、問い合わせの日までの**最後の訪問**の着地ページ・流入元で数えます。最後の訪問が30日より前なら、PV 0 の行に CV だけが出ます

> 注意：ここでの PV は、1回の訪問（30分以内のページの移動はまとめて1回）を1件と数えています。ページが見られた回数そのものではないので、Google アナリティクスの PV より少なく出ます。

## 詳細（着地ページ・流入元を押すと開く）
サマリーの表で、着地ページや流入元の文字を押すと、大きい画面で詳細が開きます。着地ページの右の小さいアイコンを押すと、そのページが別のタブで開きます。
- 上の数字：PV、閲覧回数（着地ページのとき。ページが開かれた回数）、広告からの分、訪問者の人数、2回以上来た人、CV と CV率
- **日別の PV と CV**：棒が PV、オレンジの丸が CV の件数です
- **ページの前後**（着地ページのとき）：このページの前に見ていたページと、次に見たページです。どこから入って、どこへ進んだかが分かります
- **流入元別**（着地ページのとき）／**着地ページ別**（流入元のとき）
- **端末**（スマホ・PC・タブレット）と**時間帯**
- **CV になった反響**：日付・反響媒体・キャンペーン・店舗だけを出します（お名前などは出しません）

> 注意：ページの前後と閲覧回数は、閲覧の記録を始めた日（v2.2.203 を出した日）からの分だけです。

## Meta 広告
流入元が meta・Facebook/Instagram などのときと、Meta 広告から来た人がいる着地ページでは、詳細に「Meta 広告」の表が出ます。
- 広告ごとに、画像・広告名・キャンペーン・**費用**・**表示**・**クリック**・CTR・**着地**・**CV**・**CPA**（費用 ÷ CV）を出します。見出しを押すと並べ替えができます
- 費用・表示・クリックは Meta の数字です。6時間ごとに自動で取り込みます。今すぐ取り込みたいときは、画面の上の「Meta から取り込む」を押し、数分たってから「再読み込み」を押します
- 着地・CV はサイトの記録です。Meta 広告の URL パラメータに広告ID（utm_content）が入っているので、広告ごとに結びつきます

> 注意：Meta のクリックとサイトの着地は一致しません。広告ブロッカーを使っている人や、ページが表示される前に戻った人がいるためです。

> 注意：広告の画像は数日で見られなくなることがあります。取り込み直すと戻ります。

## 見学クラウド（ie-miru）
見学クラウドの予約にも、顧客IDと広告の情報が付きます。
- 見学クラウドも1つのサイトとして登録します（許可するオリジンは https://www.ie-miru.jp）。タグは「GTM 用」を、見学クラウドに入っている GTM に入れます
- 自社のサイトから見学クラウドへのリンクを押すと、そのとき顧客IDと広告の情報がリンクに付きます。見学クラウドでもそのまま同じ顧客IDになります。見学クラウドから自社のサイトへ戻るリンクも同じです
- 予約の完了画面で、顧客IDと広告の情報が予約と一緒に届きます
- 自社のサイトから来た人の着地は、自社のサイト側で記録済みなので、見学クラウドでは数えません。広告から見学クラウドに直接来た人は、見学クラウドの着地として数えます

> 注意：GTM の中で、タグごとに動くサイトを分けてください（自社のサイト用のタグは自社のサイトだけ、見学クラウド用のタグは見学クラウドだけ）。分けないと、別のサイトのタグが動いてしまいます。

## 止める
- 「直す」で「有効」を外すと、記録を止めます。タグを貼ったままでもサイトの表示やフォームには影響しません
- サイトは消せません（記録が残るため）

> 要確認：顧客IDはお客様のブラウザに保存します。公開する前に、プライバシーポリシーへ利用目的を書く必要があります。担当者に確認してください。

