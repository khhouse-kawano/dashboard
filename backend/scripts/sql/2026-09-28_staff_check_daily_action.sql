-- =====================================================================
-- staff に check_daily_action（「要確認」を確認した日）を追加する
--
-- ⚠️⚠️ **`staff_list` ではなく `staff`。**
--   ⚠️ `staff` … ログインに使う側（mail / password / api_token を持つ）
--   ⚠️ `staff_list` … 担当営業のマスタ（店舗・役職・社員番号）
--   ⚠️ ⚠️ **間違えると誰の確認かが結び付かない。**
--
-- ⚠️ 用途: 注文営業のダッシュボードを開いたときに出す「要確認」モーダルを、
--   ⚠️ **1日1回だけ**出すため。⚠️ 「確認しました」を押した日を入れる。
--
-- ⚠️ NULL は「一度も押していない」。⚠️ **押していない人には毎回出る。**
--
-- ⚠️ 実行環境: ① レンタルサーバー（phpMyAdmin）
-- ⚠️ ⚠️ **ローカルDBにも流すこと。**
-- =====================================================================

ALTER TABLE staff
  ADD COLUMN check_daily_action DATE DEFAULT NULL;


