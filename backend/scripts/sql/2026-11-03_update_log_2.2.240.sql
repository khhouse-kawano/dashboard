## 並ぶお客様
- 架電記録の店舗が「買い:中古リノベ」のお客様です
- 最後に入れた**次回架電日が今日以前**で、その日以降にまだ**通電・未通電・SMS送信**を記録していないお客様が並びます
- 次回架電日を過ぎているお客様には「○日超過」、今日の予定のお客様には「今日の予定」の札が付きます。過ぎている日数が多いお客様ほど上に並びます
