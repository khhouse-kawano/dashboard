## SUUMO の反響は、反響ごとに1行
SUUMO の反響は、**お問い合わせ1回につき1行**で届きます。同じお客様が別の物件に問い合わせたり、資料請求のあとで見学を予約したりすると、その分だけ行が増えます（以前は、お客様1人につき最初の1行だけでした）。
- 同じお客様の2回目以降の行は、備考（虫めがね）の先頭に「**【同じお客様の反響あり】**」と、最初の反響の日付・これまでの件数・顧客DBに取り込み済みかどうかが出ます
- 複数の物件にまとめて資料請求があったときは、同じ日時の行が物件の数だけ並びます
- **キャンセルされた見学予約は出ません**。すでに届いている行があとからキャンセルになったときは、行は消えず、備考の先頭に「**【予約キャンセル 日時】**」が付きます
- 「物件名」「希望エリア」「来場予約」は、その行の反響のものです

> 注意：「同じお客様の反響あり」の行を顧客DBに取り込むと、同じお客様が2人分になります。すでに取り込み済みなら、顧客タグの「重複」を付けて、取り込まないでください。

> 要確認：備考の「取り込み済みかどうか」は、その行が届いた時点のものです。あとから取り込んだ場合は変わらないので、顧客DBでも確かめてください。

## 重複の札
「重複」の列に赤い札（例「重複 3」）が出ている反響は、**メールアドレスか携帯番号が同じ反響**が、ほかにもあるものです。注文・建売・中古の反響をまとめて見比べます。
- 数字は、同じお客様と思われる、ほかの反響の数です
- 札を押すと小さな画面が開き、相手の反響の事業（注文・建売・中古）・店舗・反響日・媒体・お名前・一致したもの（メール／携帯）・取込済みかどうかが見られます
- 選んだ期間に関係なく、これまでに届いたすべての反響と見比べます
- メールアドレスは、大文字・小文字や空白の違いを無視して見比べます
- 携帯番号は、070・080・090・050 で始まる11桁だけを見比べます（固定電話や、桁の足りない番号は見ません）
- お名前は見ていません。ご家族で同じメールアドレスを使っている場合なども「重複」になります
- 社員がテストに使った会社のメールアドレス（と、同じ反響の携帯番号）は、重複として数えません
- 個人情報削除をした反響は、重複から外れます

> 注意：新しく届いた反響や、直した連絡先は、一覧を開き直すか「再読み込み」を押すと札に反映されます。

> 要確認：札が出ていても、同じお客様とは限りません。取り込む前に、お名前や住所も確かめてください。

## 期間を変えたとき
開始月・終了月を変えると、その期間の反響だけを読み込み直します。全部の期間を一度に読まないので、画面の表示が速くなります。
- 店舗・媒体・取込状況・氏名・ふりがな・住所・電話番号などの絞り込みは、そのまま残ります
- 上の集計も、選んだ期間の分で数えます（数え方は今までと同じです）
- 読み込みが終わるまで、少しのあいだ前の期間の表示が残ることがあります

## 期間は画面のアドレスに残ります
開始月・終了月を選ぶと、ブラウザの上に出ているアドレス（URL）の末尾に、選んだ期間が付きます。
- 再読み込み（F5）をしても、同じ期間のまま開きます
- ブラウザの「戻る」を押すと、ひとつ前に選んでいた期間に戻ります
- アドレスをコピーして送ると、相手も同じ期間で反響一覧を開けます（開くのは、相手がいま選んでいる事業の反響一覧です）
- 左のメニューから「反響一覧」を押し直すと、はじめの期間（前月〜今月）に戻ります

> 注意：店舗・媒体・氏名などの絞り込みはアドレスに残りません。再読み込みすると、期間のほかははじめの状態に戻ります。

## 再読み込み
上の「🔄 再読み込み」を押すと、絞り込み（期間・店舗・氏名など）はそのままで、新しく届いた反響を読み直します。

## ブラックリストに登録する
顧客タグの「ブラックリスト」を押すと、小さな画面が開きます。**理由**を入れて「登録」を押すと登録されます。
- 理由が空のままでは登録できません
- 理由は、ヘッダーの「反響管理 → ブラックリスト設定」の**備考**に日付つきで残ります。同じ人をもう一度登録したときは、前の理由の下に書き足されます
- 外すとき（もう一度押す）は、理由の画面は出ません

## 個人情報削除
いちばん右の「個人情報削除」を押すと、その反響の**氏名・ふりがな・電話番号・メールアドレス・住所（郵便番号を含む）**を「********」に置き換え、**取込済み**にします。

> 注意：元に戻せません。押すと確認が出るので、お客様の名前を確かめてから「OK」を押してください。

> 要確認：個人情報を消してよいか（お客様からの削除の依頼など）は、社内のルールに従ってください。

