-- 実行場所: ① レンタルサーバーの phpMyAdmin
--   ⚠️ 左サイドバーで対象DBを選んでから SQL タブを開くこと。
--     information_schema のままだと #1109 になる。
--   ⚠️ PowerShell のパイプで流し込まないこと。日本語コメントが化け、
--     引用符が食われて #1064 になる。phpMyAdmin の「インポート」を使う。
--
-- 前提: 2026-09-03_ambassador.sql が適用済みであること。
-- =============================================================

-- -------------------------------------------------------------
-- 1. アンバサダーのid（URLの ?id= の生の値）
--
-- ⚠️ 既存の `ambassador_no` とは役割が違う。両方必要である。
--
--     ambassador_id … フォームのURLから届いた値を**そのまま**保存したもの。
--                     社外の誰でも書き換えられるため信用してはならない。
--                     「なぜ紐づかなかったのか」を後から調べる唯一の手掛かり。
--     ambassador_no … 上の値を ambassador_list に照合し、**実在を確認できた**
--                     ときだけ入る。集計や JOIN はこちらだけを使う。
--
-- ⚠️ INT ではなく VARCHAR にしている。'abc' や巨大な数値が来ても
--   そのまま記録するため。INT にすると MariaDB が黙って 0 に丸め、
--   改ざんされたURLの痕跡が消える。
-- -------------------------------------------------------------
ALTER TABLE `inquiry_ambassador`
  ADD COLUMN `ambassador_id` VARCHAR(64) DEFAULT NULL COMMENT 'アンバサダーのid'
  AFTER `ambassador_no`;

-- -------------------------------------------------------------
-- 2. 建築希望地
--
-- ⚠️ 住所（address）とは別物。address は現住所、build_area は
--   これから建てたい場所であり、担当店舗の割り振りに使う情報。
--   混同すると別エリアの店舗に配られる。
-- -------------------------------------------------------------
ALTER TABLE `inquiry_ambassador`
  ADD COLUMN `build_area` TEXT DEFAULT NULL COMMENT '建築希望地'
  AFTER `address`;

-- -------------------------------------------------------------
-- 3. ギフトカード進呈条件への同意
--
-- ⚠️ 3万円分のギフトカードの進呈条件に同意したかどうかの記録。
--   後から「同意していない」と言われたときに示せる唯一の証跡になるため、
--   反響が届いた時点の値を保存する。
--   NULL は「同意欄が無かった頃の古いデータ」を表す（0 とは意味が違う）。
-- -------------------------------------------------------------
ALTER TABLE `inquiry_ambassador`
  ADD COLUMN `agreed` TINYINT DEFAULT NULL COMMENT '進呈条件への同意。1=同意 0=未同意'
  AFTER `sync`;

