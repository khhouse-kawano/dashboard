-- ---------------------------------------------------------------------
-- 手順1　⚠️ 空の作業用テーブルを作る
--
-- ⚠️⚠️ **いきなり本番の表を消さない。**
--   ⚠️ CSVの取り込みが途中で失敗したとき、⚠️ **画面が空になるのを防ぐため。**
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS satbase_property_new;
CREATE TABLE satbase_property_new LIKE satbase_property;


-- ---------------------------------------------------------------------
-- 手順2　⚠️⚠️ **CSV を `satbase_property_new` に取り込む**
--
-- ⚠️ phpMyAdmin →「インポート」→ 取り込み先に ⚠️ **satbase_property_new** を選ぶ。
-- ⚠️ ⚠️ **文字コードは utf-8 にすること。**
--
-- ⚠️ 取り込んだら件数を見る（⚠️ **1,900行前後のはず**）。
--   SELECT COUNT(*) FROM satbase_property_new;
-- ⚠️⚠️ **極端に少なければここで止めること。** ⚠️ 手順3へ進まない。
-- ---------------------------------------------------------------------


-- ---------------------------------------------------------------------
-- 手順3　⚠️ 入れ替える
--
-- ⚠️⚠️ **RENAME は一瞬で終わり、途中で片方だけになることがない。**
--   ⚠️ 画面を見ている人がいても問題ない。
-- ---------------------------------------------------------------------
RENAME TABLE
  satbase_property     TO satbase_property_old,
  satbase_property_new TO satbase_property;


