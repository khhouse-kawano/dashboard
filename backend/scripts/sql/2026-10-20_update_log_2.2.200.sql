[[画面:トラッキング設定]]

## タグがすること
- サイトを見た人**全員**に、**顧客ID**を振ります（同じブラウザなら、日をまたいでも同じID）
- 広告（Google・Meta・Yahoo!）や、utm の付いたURLから来たときは、その情報を覚えます。**フォームの無いLPに着地しても**消えません
- フォームから問い合わせると、顧客IDと広告の情報が、反響と一緒に届きます
- 反響一覧（注文営業）の「流入」から、その人がいつ・どの広告から来たかを見られます（[[反響一覧]]）

> 注意：顧客IDは**サイト（ドメイン）ごと**です。kh-house.jp と day-just-house.com では別のIDになります。

## サイトを登録する
1. 「サイトを登録」を押す
2. サイト名・ブランドを入れる
3. 「許可するオリジン」に、タグを貼るサイトの **https://ドメイン** を入れる（例：https://kh-house.jp。/ 以降は不要。www の有り無しが両方あるなら2行）
4. 「保存する」→ そのサイトのタグが開きます

## タグを入れる
「タグ」を押すと、2種類のタグが出ます。サイトに合わせて**どちらか一方だけ**を使います。

- **GTM（Googleタグマネージャー）を使っているサイト**：「GTM 用」をコピーし、GTM で新しいタグ（カスタム HTML）に貼ります。トリガーは「All Pages」にして、公開します
- **GTM を使っていないサイト**：「フッター用」をコピーし、サイトの**すべてのページ**のフッターに**1回だけ**貼ります。WordPress の場合は、WPCode の Footer 欄、またはテーマのフッターに貼ります
- 入れたあと、広告のURL（例：?utm_source=test）でサイトを開くと、「直近30日の着地」「最後の着地」が増えます

> 注意：GTM に「フッター用」を貼っても動きません（GTM が中身を作り直すときに、サイトを見分ける情報が消えるため）。GTM には必ず「GTM 用」を使ってください。

> 注意：GTM とフッターの両方に入れると、着地が2回記録されます。GTM に切り替えたら、フッターのタグは外してください。

> 注意：LP がサイトと別の仕組み（単体のページなど）で作られていて、GTM もフッターも入っていない場合は、その LP にも入れてください。LP とフォームのドメインが違うと、広告の情報と顧客IDはフォームまで届きません。

> 注意：ここに無いドメインからの記録は保存しません。ドメインを変えたら「直す」で許可するオリジンも直してください。

## 止める
- 「直す」で「有効」を外すと、記録を止めます。タグを貼ったままでもサイトの表示やフォームには影響しません
- サイトは消せません（記録が残るため）

> 要確認：顧客IDはお客様のブラウザに保存します。公開する前に、プライバシーポリシーへ利用目的を書く必要があります。担当者に確認してください。

