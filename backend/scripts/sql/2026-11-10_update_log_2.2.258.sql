## 反響を登録する
売り反響・買い反響の画面の右上の「**反響を追加**」を押すと、登録の画面が開きます。
- 受信日は必須です。売り反響は売主名か物件所在地のどちらか、買い反響は顧客名が必須です
- 次回連絡日と次回アクションも必須です（編集のときと同じ）
  - 次回連絡日の欄のすぐ下の「明日」「3日後」「1週間後」「2週間後」「1ヶ月後」を押すと、今日から数えた日付が入ります（売り反響・買い反響・商談案件の編集画面も同じ）
- 同じ連絡先（電話・メール）、または同じ名前で同じ受信日の反響がすでにあると、確かめる画面が出ます。別の人なら「OK」で登録できます
- 登録のときに選べる段階は、はじめのほうの段階だけです。媒介受託・購入申込・成約・追客終了は、登録したあとに一覧で変えます
- 入れた電話番号・メールアドレスは、一覧の「連絡先」にも「電話 / メール」の形で入ります。あとで編集画面で電話番号・メールアドレスを直したときも、連絡先は同じ形に作り直されます（電話番号・メールアドレスを変えずに保存したときは、連絡先はそのままです）
- 今日の架電キュー・架電ナビに出る電話番号は、反響の「連絡先(電話)」を先に使います。空のときは連絡先から拾います

## 売り反響（一括査定）
媒介獲得台帳へつなぐのは、**売り反響の画面だけ**です。一覧の「**媒介紐付**」の列で、つながりが分かります。
- 「**台帳No.〇**」：媒介獲得台帳につながっています
- 「**🔗 媒介紐付**」：押すと、媒介獲得台帳へ登録する画面が開きます
- 「**未転記→台帳へ**」（だいだい色）：段階は媒介受託なのに、台帳がまだありません。押すと同じ画面が開きます
- 「―」：追客終了の反響です

### 媒介獲得台帳へ登録する
1. 「媒介紐付」を押す（一覧で段階を「**媒介受託**」に変えたときと、編集画面で媒介受託にして保存したときも、同じ画面が開きます）
2. 売り反響の売主・連絡先・所在地・区分・査定額・担当が、台帳の項目に入った状態で開きます
3. 次の項目を確かめて直す（**すべて必須**）
   - 媒介の種類（専属専任媒介／専任媒介／一般媒介）
   - 媒介契約日（未来の日付は入れられません）
   - 有効期間の満了日：最初は「契約日の3か月後の前日」が入ります。専属専任媒介・専任媒介は3か月を超えられません（宅建業法）。一般媒介は超えると確かめる画面が出ます
   - 売出価格（1円以上）
   - 担当者・売主・物件の所在地・物件の種別
   - 種別がマンションのときは、**建物名**も必須です
   - 下の「媒介物件」の欄（地番・建物名・部屋番号・土地面積・建物面積・築年・間取り）も確かめます。一括査定の詳細にあった値は、初めから入っています
4. 「**登録**」を押すと、媒介獲得台帳に1行が作られ（台帳の No. は自動・現況は「情報整理中」）、売り反響の段階が「媒介受託」になります。台帳と段階は**必ず一緒に**保存されます（片方だけが保存されることはありません）
5. 「**媒介獲得台帳で No.〇 を開く**」を押すと、媒介獲得台帳でその行が黄色で出ます

### 媒介物件（同じ物件の履歴）
登録すると、台帳は「媒介物件」（物件そのもの）に紐づきます。**以前に同じ物件を媒介・買取していれば、その物件に紐づき**、登録の画面に「以前の台帳と同じ物件に紐づけました（台帳 No.〇）」と出ます。
- 同じ物件かどうかは、**種別と住所**で見ます。住所の空白・全角半角・「丁目・番地・番・号」と「-」の違いは、そろえて比べます
- マンションは、建物名と部屋番号も比べます。地番を入れたときは、地番で比べます
- 住所に番地が無いとき（「鹿児島市」だけなど）は、ほかの物件とまとめません
- 媒介獲得台帳の一覧では、同じ物件に台帳が2件以上あると、住所の横に「**同じ物件の台帳 N件**」と出ます。押すと、その台帳の No. が出ます

- 足りない項目があると、画面の上に赤で項目の名前が出て、登録できません
- 一般媒介で、明示型のときは「他の依頼先」も入れられます（台帳の備考に入ります）
- 「キャンセル」を押すと、何も変わりません。一覧で媒介受託を選んだときは段階も元に戻り、編集画面からのときは段階以外の項目だけが保存されています
- すでに台帳に作られた反響は、段階を変え直しても、もう1行は作られません
- 買取（自社で買い取る）は、この画面では選べません。「買取案件へ」を使います
- 段階を「**追客終了**」にすると、理由を聞かれます（他決／辞退・売却中止／連絡不能／対象外／その他）。理由は「失注・他決の分析」に出ます。追客終了から別の段階に戻すと、理由は消えます

> 注意：今日の架電キュー・チームサマリーの編集画面では、段階に「媒介受託」を選べません。売り反響の画面の「媒介紐付」から登録してください。

## 買い反響（ポータル）
### ポータルの問い合わせは自動で台帳につながります
SUUMO・HOME''S・アットホームから届いた買い反響は、問い合わせの物件番号（いえらぶの物件番号と同じ）で、その物件の媒介獲得台帳に**自動で**紐づきます。
- 台帳が、いえらぶの物件とつながっていることが条件です（この記事の「媒介獲得台帳」の「いえらぶの物件とつなぐ」）
- 30分ごとと、台帳を保存したときに動きます。すでに紐づいている買い反響は変えません
- メールで届いた反響や、電話・来店の反響は、自動ではつながりません。下の手順で紐づけてください

### 問合せ物件を媒介獲得台帳の物件に紐づける
ポータルに載せる前の物件や、電話・来店の反響のように、どの物件への問い合わせかを自動で拾えないときは、編集画面で紐づけます。
1. 買い反響の顧客名を押して編集画面を開く
2. 「**問合せ物件（媒介獲得台帳）**」の欄に、台帳No.・売主名・所在地の一部・いえらぶの物件番号を入れる（例：「吉野 3丁目」「125」「274111」）。空白で区切ると、すべての言葉に当てはまる物件だけに絞れます
3. 下に出た候補（台帳No.／売主／所在地／売出価格／媒介の種類／現況）を押す
4. 「保存する」を押す

- 紐づけると、欄に「📝 No.〇／売主…」の札が出ます。「**解除**」で外せます（問合せ物件名は残ります）
- 「問合せ物件名」が空なら、台帳の物件名（自社名義なら括弧の中の物件名、それ以外は所在地）が入ります。すでに入っていて違うときは、置き換えるかを聞きます。他社物件・未定のときは、問合せ物件名だけを入れてください
- 媒介終了の台帳は候補に出ません
- 買い反響の一覧の「問合せ物件」に、紐づいている反響は「📝No.〇」の札が出ます
- この欄で紐づけた買い反響は、台帳と同じ「媒介物件」にもつながります
- 媒介獲得台帳の「🤝買付登録」の自社客付けで選んだ買い反響も、まだどの台帳にも紐づいていなければ、その台帳に紐づきます

> 注意：ポータルの問い合わせ以外は、物件名や住所が合っているだけでは紐づきません。この欄か、媒介獲得台帳の「買付登録」で紐づけてください。

### 段階と商談案件
- 段階を「**購入申込**」にすると、「商談案件管理へ転記しますか？」と聞かれます。「OK」で、**商談案件管理に「買」の案件が1件作られます**。物件名・価格を確かめてください
- その場で転記しなかったときは、段階の下の「**案件へ転記**」を押すと作れます。作った反響には「案件に連携済み」と出ます
- 「追客終了」の理由は、売り反響と同じように保存されます

> 注意：段階の名前は以前のアプリと同じです（通電済・内見済 など）。名前が違うと歩留まりの数に入らないため、選択肢にない名前は使わないでください。

## 商談案件管理
[[月次売上管理（不動産企画係）]] の数字のもとになる、商談案件の一覧です。
- 1行が1案件です。成約価格・進捗フェーズ・契約日・決済予定日・リフォームの受注額と粗利は、一覧のまま直せます（自動で保存）
- 仲介手数料は、成約価格から自動で計算します（800万円以下は30万円、それより上は価格×3％＋6万円・税抜）。手入力した額は黄色で出ます
- 行の左端の「**編集**」か、**物件名**を押すと編集画面が開きます。共同担当と売上の割合、次回アクションなども直せます
- 「**精算書**」を押すと、決済精算書の画面が開きます。開くたびに、その案件の値から作り直します
  - 種別が「売」なら売主と売主側の請求、「買」なら買主と買主側の請求で開きます。相手方の名前・固定資産税・決済場所などは空欄なので、入れてください
  - 仲介手数料は、案件の仲介手数料（手入力の額を含む）に合うように、値引きの欄で調整して入ります
  - 決済予定日は、決済日と請求書の支払期日に入ります
- この画面では、案件を新しく作れません。案件は、買い反響の「購入申込」か、媒介獲得台帳の「買付登録」（下）から作ります。どの反響から来たお客様かを、あとで辿れるようにするためです

## 媒介獲得台帳
- 媒介も、この画面では新しく作れません。必ず売り反響を「媒介受託」にして作ります。売主がどの反響から来たかを、あとで辿れるようにするためです
- 一覧は、**媒介契約日の新しい順に、全件を1枚**で出します（ページの切り替えはありません）。媒介契約日が入っていない台帳は、いちばん下に出ます
- 担当欄は、反響・商談案件と同じ**担当者名**（空白なし）です。媒介紐付でも、台帳の編集画面で選び直しても、同じ形で入ります

### いえらぶの物件とつなぐ
媒介獲得台帳の物件と、いえらぶに登録した物件（中古住宅専門店の物件）をつなぎます。つながると、ポータルから届いた買い反響が、その台帳に自動で紐づきます。
- 台帳を登録したあと、いえらぶに物件を登録すると、**所在地と種別**（マンションは建物名・部屋番号も）が同じ物件に、自動でつながります
  - 30分ごとと、台帳を保存したときに動きます。すぐつなぎたいときは、一覧の上の「**いえらぶと突き合わせ**」を押します
  - 所在地の空白・全角半角・「丁目・番地・番・号」と「-」の違い、先頭の「鹿児島県」はそろえて比べます
- 一覧の「**ポータル連携（いえらぶ）**」の列に、つながり方が出ます。押すと編集画面が開きます
  - 「**No.〇〇〇〇〇〇**」：いえらぶの物件番号につながっています
  - 「**要確認 N件**」：所在地が近い物件が見つかりましたが、1件に決められません（同じ住所に区画が2つある、番地の細かさが違う、種別が違う など）。編集画面で選んでください
  - 「**いえらぶ未採番**」：所在地が同じ物件が、いえらぶにまだありません。いえらぶに登録すると、自動でつながります
  - 「**該当なし**」：いえらぶに載せない物件にしたもの
- 一覧の上の「⑥ いえらぶ」で、要確認・未採番の台帳だけに絞れます

編集画面の「**掲載物件連携（いえらぶの物件）**」の欄
- いえらぶの物件番号・物件名・所在地の一部で探して選べます
- まだつながっていない台帳には、所在地が近い物件の候補が出ます。押すとつながります（「保存する」で保存）
- 「**外す**」でつながりを外せます。外した台帳や、人が選んだ台帳は、自動で変えられません
- いえらぶに載せない物件は「**該当なし**」を押して保存します

> 注意：いえらぶに物件を登録するときは、台帳の編集画面の「**所在地をコピー**」「**建物名をコピー**」を押して、いえらぶの入力欄に**貼り付けて**ください（Ctrl+C・Ctrl+V）。手で打ち直すと表記がずれて、自動でつながらず「要確認」「いえらぶ未採番」に残ります。

### 期限の見方
台帳ごとに、次の3つの期限を出します。期限が近いと**黄色**、過ぎると**赤**になります。媒介終了・成約完了の台帳には出しません。
- **レインズ（REINZ の列）**：まだ登録していない専属専任媒介・専任媒介に「要登録 11/12（あと3日）」のように出ます
  - 期限は、媒介契約日の翌日から数えて、専属専任媒介は**5営業日目**、専任媒介は**7営業日目**です
  - 休業日（[[設定（不動産企画係）]] の「休業日」）は数えません
  - レインズ登録日を入れると「登録済み」になります
- **販売報告（販売報告の列）**：次に売主へ報告する期限です
  - 専属専任媒介は**7日**、専任媒介は**14日**ごとです
  - 初回は媒介契約日から、2回目からは台帳の「直近報告日」から数えます。報告したら、台帳の編集画面で直近報告日を入れてください
  - 一般媒介には出ません
- **契約満了予定・残日数・更新状態**：有効期間の満了日です
  - 媒介紐付で入れた満了日を使います。入っていない台帳は、媒介契約日の3か月後の前日で数えます
  - 満了日の**14日前**から「期限間近」、過ぎると「期限切れ」です
  - 一般媒介にも出します

### 買付が入ったら（買付登録）
媒介獲得台帳の「客付・案件」の列の「**🤝買付登録**」を押します。編集の画面で現況を「買付有」にして保存したときも、買付登録の画面を開くか聞かれます。
- **他社客付け**（他社のお客様が買う）：客付け会社名（必須）・担当者・連絡先を入れます。商談案件管理に「**売**」の案件が1件できます（自社は売主側の片手）
- **自社客付け**（自社の買い反響のお客様が買う）：買い反響から買主を選びます。商談案件管理に「**売**」「**買**」の案件が2件できます（両手）。選んだ買い反響も「購入申込」になり、この物件とつながります
- どちらも、買付金額（必須）・契約希望日・引渡希望日・買主・物件名（必須）・自社担当を入れます。契約希望日が、商談案件の契約日（月次売上を数える月）になります
- 登録すると、台帳の現況は「買付有」になり、「客付・案件」の列に「案件No.」が出ます
- 自社が売主の物件（媒介種別が「買取」、売主が自社名義）は、仲介手数料を計上しない印が最初から付きます

買付が白紙になったときは、「案件No.」を押して「**連携を解除**」します。商談案件そのものは消えません（必要なら商談案件管理で失注にします）。解除すると、もう一度登録できます。

## 売り反響から買取へ（自社買取）
自社で買い取る売り反響は、売り反響の一覧で「**買取案件へ**」を押します。このボタンは、「媒介受託」で媒介獲得台帳ができた反響にだけ出ます。
- 押すと、その台帳の媒介種別が「**買取**」になり、「買取再販案件」の画面に案件が1件できます（ステータスは「仕入検討」。売主・所在地・種別・担当・査定価格が入ります）
- 同じ台帳には、2件目はできません
- できた案件で、買取価格・建物の価格・費目を入れてください

> 注意：買取再販案件の画面でも、新しく作れません。必ず売り反響から作ります。どの売主から仕入れたかを、あとで辿れるようにするためです。
- 上の「担当者別サマリー」は、失注を除いた案件の数と契約率、リフォームの受注額・粗利です

### 失注にする
1. 進捗フェーズで「失注」を選ぶ
2. 確認の画面で「OK」を押すと、編集の画面が開く
3. 「失注理由」を選び（必須）、必要なら「失注の詳細」を入れて保存する

失注理由は [[失注・他決の分析（不動産企画係）]] に出ます。

> 注意：次回アクション（予定日・内容）は、失注・決済完了以外の案件では必須です。

