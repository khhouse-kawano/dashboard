-- ===========================================================
-- medium_kaeru に「グラフ表示」の列を追加
--
-- 2026-09-11
--
-- ─────────────────────────────────────────────
-- 何のための列か
--
--   販促媒体別動向（建売）の
--   frontend/src/components/customerTrend/CustomerTrendKaeru.tsx で、
--   **表の行とグラフの系列に出す販促媒体**を決めるために使う。
--
--   ⚠️⚠️ それまではフロントに直書きしていた。
--     const displayMediums = ['SUUMO', `HOME'S`, 'ALLGRIT', 'アットホーム'];
--     媒体の増減は運用側で起こるため、直書きは必ず腐る。
--     （2026-09-09 に utils/setStaffLength.ts の課の一覧で同じ問題が起きている）
-- ─────────────────────────────────────────────
--
-- ⚠️⚠️ **`ALLGRIT` という値は medium_kaeru に無い。実データは `公式LINE`。**
--   画面で ALLGRIT と出ているのは CustomerTrendKaeru.tsx の
--   mediumFormate() が表示名だけ差し替えているためである。
--   ⚠️ `ALLGRIT` を 1 にしても**1行も更新されない**。必ず `公式LINE` を使うこと。
--
-- ⚠️ `athome` も mediumFormate() で `アットホーム` に差し替えている。
--   どちらの表記で登録されているかは下の確認クエリで必ず目視すること。
--
-- 実行順: このファイル単体で完結。
-- 冪等性: ⚠️ ADD COLUMN に IF NOT EXISTS を付けている（MariaDB 10.0+）。
--         UPDATE も同じ値を入れ直すだけなので、二重実行して差し支えない。
-- ===========================================================

ALTER TABLE `medium_kaeru`
  ADD COLUMN IF NOT EXISTS `show_graph` TINYINT DEFAULT 0 COMMENT 'グラフ表示';

-- ===========================================================
-- 実行前の確認
-- ===========================================================
-- ⚠️⚠️ **先にこれを実行して、実データの表記を目で見ること。**
--   下の UPDATE は完全一致なので、表記が1文字でも違うと 0 行更新になり、
--   **エラーも出ないまま「グラフに何も出ない」状態**になる。
SELECT `medium`, `show_graph` FROM `medium_kaeru` ORDER BY `medium`;

-- ===========================================================
-- グラフ・表に出す媒体を 1 にする
-- ===========================================================
-- ⚠️ HOME'S はアポストロフィを含む。二重引用符で囲むか '' でエスケープする。
--   ここでは "HOME'S" と書いている（MySQL/MariaDB の既定では文字列リテラル）。
--   ⚠️ ANSI_QUOTES が有効な環境では識別子と解釈されるので、その場合は
--     'HOME''S' に書き換えること。
UPDATE `medium_kaeru`
   SET `show_graph` = 1
 WHERE `medium` IN ('SUUMO', "HOME'S", 'アットホーム', '公式LINE');

-- ===========================================================
-- 実行後の確認
-- ===========================================================
-- ⚠️⚠️ **information_schema は使わない。**
--   ① レンタルサーバー（Xserver 共用）の DB ユーザーには参照権限が無く
--     #1044 - ... 'information_schema' データベースへのアクセスを拒否します
--   になる。SHOW COLUMNS なら権限が要らない。
SHOW COLUMNS FROM `medium_kaeru` WHERE `Field` = 'show_graph';

-- ⚠️ **4行返ることを確認すること。**
--   4行に満たなければ表記が違う。上の SELECT の結果と突き合わせる。
SELECT `medium`, `show_graph` FROM `medium_kaeru` WHERE `show_graph` = 1 ORDER BY `medium`;
