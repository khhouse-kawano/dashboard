-- =====================================================================
-- funding_plan テーブル：⑨段取り表の「予定日を直接指定」を保存する列を足す
--
-- ⚠️⚠️ **改修版の資金計画書（2026-09-21）で追加された機能。**
--   ⚠️ STEP2 資金概算提案 〜 STEP7 ローン事前審査承認 は、
--     ⚠️ **日数ではなく予定日そのものをカレンダーで選ぶ**方式になった。
--   ⚠️ STEP8 ご契約 以降は従来どおり「前のステップからの日数」で自動計算する。
--   ⚠️ 空欄に戻すと自動計算に戻る（画面の `flowDates()`）。
--
-- ⚠️⚠️ **この列が無いと、保存は成功するのに予定日だけ消える。**
--   ⚠️ 許可リスト（backend-express/src/features/fundingPlan/columns.ts）が
--     「列として存在するものだけ」を採用するため、⚠️ **エラーは出ない。**
--   ⚠️ 面談中に入力した予定日が、開き直すと消えている状態になる。
--
-- ⚠️ 型は LONGTEXT（JSON）。⚠️ `w_days` / `w_done` と同じ持ち方である。
--   ⚠️ 中身は FLOW と同じ長さの配列で、要素は "2026-10-01" か空文字。
--
-- ⚠️ 実行環境: ① レンタルサーバー（phpMyAdmin）
-- =====================================================================

ALTER TABLE funding_plan
  ADD COLUMN w_dates LONGTEXT DEFAULT NULL
  COMMENT '⑨段取り表 STEP2〜7の予定日。FLOWと同じ長さの配列。空文字なら日数から自動計算';

-- =====================================================================
-- 確認用
-- ⚠️ w_start / w_days / w_done / w_dates の4行が出ること
-- =====================================================================
SHOW COLUMNS FROM funding_plan LIKE 'w\_%';
