## 期間と読み込み（販促媒体別・店舗別）
販促媒体別反響推移と店舗別反響推移は、開始月・終了月で選んだ期間の分だけを読み込みます（前より早く開きます）。
- はじめは、11か月前〜今月です。開始月・終了月の欄には、いま選んでいる月が出ます
- 期間を変えると読み込み直します。読み込みが終わるまで、表の代わりに「読み込み中…」と出ます
- 「昨年実績を表示」「広告費を表示」は、チェックを入れたときに、前の年の分・広告費を読み込みます。チェックを外したときは読み込み直しません
- 課・ブランド・店舗・販促媒体の絞り込み、「ポータル反響のみ表示」（販促媒体別）、「併売店をまとめる」「期間を反転」、グラフは読み込み直しません。選んだものはそのまま残ります
- 「全期間」の列は、選んだ期間の合計です
- お客様の詳細を閉じると、同じ期間のまま読み込み直します

## 期間は画面のアドレスに残ります（販促媒体別・店舗別）
開始月・終了月を選ぶと、ブラウザの上に出ているアドレス（URL）の末尾に、選んだ期間が付きます。
- 再読み込み（F5）をしても、同じ期間のまま開きます
- ブラウザの「戻る」を押すと、ひとつ前に選んでいた期間に戻ります
- アドレスをコピーして送ると、相手も同じ期間で開けます
- 左のメニューから「販促媒体別反響推移」「店舗別反響推移」を押し直すと、はじめの期間（11か月前〜今月）に戻ります

> 注意：課・店舗・チェックなどはアドレスに残りません。再読み込みすると、期間のほかははじめの状態に戻ります。

## 月の並び（販促媒体別・店舗別）
販促媒体別反響推移と店舗別反響推移の表は、左から「全期間」、続いて新しい月から古い月の順に並びます。左端は終了月です（販促媒体別は2026年11月から）。
- 「期間を反転」にチェックを入れると、古い月から新しい月の順に変わります
- 並びを変えても、数は変わりません
- 開始月・終了月の選択肢も、新しい月が上に並びます

> 注意：販促媒体別の「グラフ」と、店舗別の「サマリ」で開くグラフと表は、チェックに関係なく古い月から順に並びます。

